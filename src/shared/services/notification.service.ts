import { FastifyInstance } from 'fastify';

export type NotificationType =
  | 'SHIFT_ASSIGNED'
  | 'GPS_FAILURE_ALERT'
  | 'GPS_RECOVERED'
  | 'ATTENDANCE_EXCEPTION'
  | 'CORRECTION_RESOLVED'
  | 'LEAVE_REQUESTED'
  | 'LEAVE_APPROVED'
  | 'LEAVE_REJECTED'
  | 'PAYROLL_READY'
  | 'PAYROLL_APPROVED'
  | 'PAYROLL_PAID';

export interface CreateNotificationInput {
  organizationId: string;
  userId: string;
  type: NotificationType;
  title: string;
  body: string;
  /**
   * Deduplication key. The backend uses a short-lived marker to avoid
   * re-broadcasting the same alert, and the Android client persists it as a
   * unique key in its local Room database.
   */
  dedupeKey: string;
  metadata?: Record<string, unknown> | null;
}

/** In-memory deduplication cache: dedupeKey -> expiry timestamp (ms). */
const dedupeCache = new Map<string, number>();

/** Automatically prune expired keys every 30 minutes. */
setInterval(() => {
  const now = Date.now();
  for (const [key, expiresAt] of dedupeCache.entries()) {
    if (expiresAt <= now) {
      dedupeCache.delete(key);
    }
  }
}, 30 * 60 * 1000).unref();

/**
 * Purpose: Broadcasts an operational notification over the real-time WebSocket event stream with 24-hour in-memory deduplication.
 * How it works: Checks `dedupeCache` Map. If `dedupeKey` is active and unexpired, skips re-broadcasting.
 * Otherwise, records dedupeKey with 24-hour TTL and publishes a `notification` domain event targeting `input.userId`.
 * Note: Notifications are NOT stored in PostgreSQL; client devices store notifications in local Room DB.
 *
 * @param fastify Fastify instance.
 * @param input CreateNotificationInput (`organizationId`, `userId`, `type`, `title`, `body`, `dedupeKey`, optional `metadata`).
 * @returns Promise resolving to `true` if broadcast; `false` if deduplicated or error occurred.
 */
export async function createNotification(
  fastify: FastifyInstance,
  input: CreateNotificationInput
): Promise<boolean> {
  try {
    const now = Date.now();
    const existingExpiry = dedupeCache.get(input.dedupeKey);
    if (existingExpiry && existingExpiry > now) {
      return false; // Deduplicated
    }

    // Set deduplication key for 24 hours (86,400,000 ms)
    dedupeCache.set(input.dedupeKey, now + 86_400_000);

    if (typeof fastify.publishDomainEvent === 'function') {
      await fastify.publishDomainEvent({
        type: 'notification',
        organizationId: input.organizationId,
        userIds: [input.userId],
        payload: {
          id: input.dedupeKey,
          type: input.type,
          category: input.type,
          title: input.title,
          body: input.body,
          message: input.body,
          dedupeKey: input.dedupeKey,
          metadata: input.metadata ?? null,
          createdAt: new Date().toISOString(),
        },
      });
    }

    return true;
  } catch (err) {
    fastify.log.warn({ err }, 'Failed to broadcast notification');
    return false;
  }
}

/**
 * Purpose: Broadcasts an operational notification to multiple recipient user IDs in sequence.
 * Usage Note: Utility function for multi-recipient notification dispatches.
 * How it works: Iterates through array of `userIds` and invokes `createNotification` with the payload generated by `build(userId)`.
 *
 * @param fastify Fastify instance.
 * @param userIds Array of target user ID strings.
 * @param build Callback producing a `CreateNotificationInput` for each recipient user ID.
 */
export async function createNotificationForUsers(
  fastify: FastifyInstance,
  userIds: string[],
  build: (userId: string) => CreateNotificationInput
): Promise<void> {
  for (const userId of userIds) {
    await createNotification(fastify, build(userId));
  }
}
